def build_dispatcher_postimage(raw, lifecycle_raw):
    require(digest(raw) == NATIVE_PREIMAGES['nox_dispatcher_t855u.py'],
            'BASE_DISPATCHER_PREIMAGE')
    try:
        source = raw.decode('utf-8')
    except UnicodeError:
        raise RuntimeError('HOLD_SUBAGENT_FRESH_BASE_DISPATCHER_ENCODING')
    tree = ast.parse(source)
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module)
    for optional in ('owner_media_runtime', 'owner_s03_gateway'):
        require(optional not in imported, 'UNPINNED_OPTIONAL_SOURCE_' + optional.upper())
    lifecycle = types.ModuleType('owner_task_lifecycle_candidate')
    outbox_name = 'owner_event_outbox'
    missing = object()
    previous = sys.modules.get(outbox_name, missing)
    # The patcher has no runtime outbox callsite. A stub avoids importing or
    # initializing any service code; the installed binder verifies the real
    # outbox file against LIFECYCLE_SOURCE_PINS at startup.
    sys.modules[outbox_name] = types.ModuleType(outbox_name)
    try:
        exec(compile(lifecycle_raw, '<pinned-owner-task-lifecycle>', 'exec'), lifecycle.__dict__)
    finally:
        if previous is missing:
            sys.modules.pop(outbox_name, None)
        else:
            sys.modules[outbox_name] = previous
    patcher = getattr(lifecycle, 'patch_dispatcher', None)
    require(callable(patcher), 'LIFECYCLE_PATCHER_INTERFACE')
    updated = patcher(source, NATIVE_PREIMAGES['nox_dispatcher_t855u.py'],
                      dict(LIFECYCLE_SOURCE_PINS))
    require(updated.count(lifecycle.PATCH_MARKER) == 1, 'LIFECYCLE_PATCH_MARKER')
    compile(updated, '<patched-owner-dispatcher>', 'exec')
    return updated.encode('utf-8')


def _metadata(path):
    path = Path(path)
    require(not any(parent.is_symlink() for parent in (path, *path.parents)),
            'TARGET_SYMLINK')
    try:
        info = path.lstat()
    except OSError:
        raise RuntimeError('HOLD_SUBAGENT_FRESH_TARGET_METADATA')
    require(stat.S_ISREG(info.st_mode) and info.st_nlink == 1,
            'TARGET_FILE_TYPE_OR_LINKS')
    try:
        attrs = os.listxattr(path, follow_symlinks=False)
    except (AttributeError, OSError, TypeError):
        raise RuntimeError('HOLD_SUBAGENT_FRESH_XATTR_READ')
    require(not attrs, 'TARGET_XATTRS_UNSUPPORTED')
    return {'mode': stat.S_IMODE(info.st_mode), 'uid': info.st_uid, 'gid': info.st_gid,
            'dev': info.st_dev, 'ino': info.st_ino, 'nlink': info.st_nlink,
            'size': info.st_size, 'xattrs': []}


def _same_inode_metadata(actual, expected):
    return all(actual.get(key) == expected.get(key)
               for key in ('mode', 'uid', 'gid', 'dev', 'ino', 'nlink', 'size', 'xattrs'))


def atomic_replace_existing(h, path, expected_raw, replacement, expected_metadata,
                            preserve_metadata):
    """CAS replace an existing regular file while retaining mode/owner/group."""
    path = Path(path)
    require(h.read(path) == expected_raw, 'WRITE_PREIMAGE')
    before = _metadata(path)
    require(_same_inode_metadata(before, expected_metadata), 'WRITE_METADATA_PREIMAGE')
    fd, temporary = tempfile.mkstemp(prefix='.nox-subagent-transition-', dir=path.parent)
    try:
        temporary_owner = os.fstat(fd)
        if (temporary_owner.st_uid, temporary_owner.st_gid) != (preserve_metadata['uid'], preserve_metadata['gid']):
            os.fchown(fd, preserve_metadata['uid'], preserve_metadata['gid'])
        os.fchmod(fd, preserve_metadata['mode'])
        with os.fdopen(fd, 'wb') as stream:
            fd = -1
            stream.write(replacement)
            stream.flush()
            os.fsync(stream.fileno())
        # The maintenance lease is exclusive; still recheck the target before
        # rename so concurrent edits fail closed.
        require(h.read(path) == expected_raw and
                _same_inode_metadata(_metadata(path), expected_metadata),
                'WRITE_PREIMAGE_CHANGED')
        os.replace(temporary, path)
        directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        if fd >= 0:
            os.close(fd)
        if os.path.exists(temporary):
            os.unlink(temporary)
    readback = h.read(path)
    after = _metadata(path)
    require(readback == replacement and
            all(after[key] == preserve_metadata[key] for key in ('mode', 'uid', 'gid')),
            'WRITE_METADATA_READBACK')
    return after


