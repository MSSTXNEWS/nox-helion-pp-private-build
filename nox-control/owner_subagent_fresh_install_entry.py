    require(admission.get('schema') == 'NOX_OWNER_TRAINING_ADMISSION_V1'
            and profile.get('model_id') == 'Qwen/Qwen3.5-9B'
            and profile.get('training_service') == TRAIN_SERVICE
            and profile.get('physical_gpu') == 1, 'CURRENT_QWEN_SCOPE')
