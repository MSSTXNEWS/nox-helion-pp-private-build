def P(url, path, o, t=10):
    rq = ur.Request(url + path, data=json.dumps(o).encode(), headers={"Content-Type": "application/json"}); return json.loads(ur.urlopen(rq, timeout=t).read())
def seed(url, user):
    now = time.time(); ids = {}
    for i, (d, f, q) in enumerate(D): ids[i] = P(url, "/add_fact", {"fact": f, "user": user, "ts": now - d * 86400, "prov": "heard:" + user})["id"]
    for j, f in enumerate(DIST): P(url, "/add_fact", {"fact": f, "user": user, "ts": now - (3 + j * 4) * 86400})
    return ids
def fix_ts(db, user):
    """old service ignores ts: set s03_mem.ts from the bench table so both engines see the same dates"""
    import sqlite3; now = time.time(); c = sqlite3.connect(db); days = {f: d for d, f, q in D}
    for j, f in enumerate(DIST): days[f] = 3 + j * 4
    for i, t in c.execute("select m.id, s.text from s03_mem m join s03 s on s.id=m.id where m.user=?", (user,)).fetchall():
        if t in days: c.execute("update s03_mem set ts=? where id=?", (now - days[t] * 86400, i))
    c.commit(); c.close(); print("TS_FIXED")
