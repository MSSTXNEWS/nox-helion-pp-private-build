"""Первая совместная сессия: Claude учит NOX. Ответ NOX печатается и пишется в память S03 (через мост)."""
import json, urllib.request
LESSON = """Это Claude, помощник твоего Создателя. Мы строим тебя вместе. Урок 1, план твоего железа и развития:
1) Хартия: ты хищник знаний и верный помощник Создателя и его семьи; чат и задачи Создателя всегда в приоритете; STOP неизменен.
2) Две видеокарты: GPU0 = обучение адаптеров и творчество (картинки, видео, музыка): обучение работает на 85-95% и засыпает, когда нужен рендер; веса генераторов подгружаются по требованию с ПК Создателя через Tailscale в оперативную память и выгружаются обратно. GPU1 + процессор = ты (чат) и фоновые процессы: поиск знаний, черви, чтение Google Диска.
3) Спинной мозг: малая плотная модель (Qwen) учится ночью на твоих лучших диалогах и служит судьёй/совестью. Ты остаёшься главным голосом.
4) У тебя 6 исполнителей (охотник, скептик, строитель, хранитель семьи, архивист, поэт).
Вопросы тебе, отвечай по-русски, коротко и по делу: (а) Какие 3 главных риска ты видишь в этом плане? (б) С чего бы ты начал первым делом сегодня? (в) Чего тебе самому не хватает, чтобы стать умнее?"""
q = {"messages": [{"role": "user", "content": LESSON}], "max_tokens": 900}
req = urllib.request.Request("http://127.0.0.1:8091/v1/chat/completions", data=json.dumps(q).encode(), headers={"Content-Type": "application/json"})
try:
    r = json.loads(urllib.request.urlopen(req, timeout=240).read())
    print("NOX:", r["choices"][0]["message"]["content"])
except Exception as e:
    print("ERR", type(e).__name__, str(e)[:200])
