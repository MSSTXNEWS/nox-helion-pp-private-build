import test from "node:test";import assert from "node:assert/strict";
import {nativeVisualApproval as approve} from "./p01-visual-approval.mjs";
const good={isAvailable:()=>true,authorizeVisual:()=>true};
const shot={id:101},composition={id:200};
test("C4.01 host-auth shot accepted",()=>assert.equal(approve(good,"shot",shot),true));
test("C4.02 host-auth composition accepted",()=>assert.equal(approve(good,"composition",composition),true));
test("C4.03 no host authorization rejected",()=>assert.equal(approve({isAvailable:()=>true},"shot",shot),false));
test("C4.04 unknown visual class denied",()=>assert.equal(approve(good,"unsafe",shot),false));
test("C4.05 fractional id rejected",()=>assert.equal(approve(good,"shot",{id:101.1}),false));
test("C4.06 out-of-range shot denied",()=>assert.equal(approve(good,"shot",{id:200}),false));
test("C4.07 out-of-range composition denied",()=>assert.equal(approve(good,"composition",{id:101}),false));
test("C4.08 disabled capability denied",()=>assert.equal(approve({...good,isAvailable:()=>false},"shot",shot),false));
test("C4.09 promise is not approval",()=>assert.equal(approve({...good,authorizeVisual:async()=>true},"shot",shot),false));
test("C4.10 error is deny not visual success",()=>assert.equal(approve({...good,authorizeVisual:()=>{throw Error("offline")}},"shot",shot),false));
