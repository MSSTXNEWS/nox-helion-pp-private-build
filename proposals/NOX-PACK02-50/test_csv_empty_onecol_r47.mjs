import assert from "node:assert/strict";
import { execute, IDS } from "./ops.mjs";
const stringify = rows => execute("data.csv.stringify", JSON.stringify(rows)).result;
const parse = text => execute("data.csv.parse", text).result;
const one = [{note:""}];
assert.equal(stringify(one), 'note\n""');
assert.deepEqual(parse(stringify(one)), one);
const many = [{id:"1",note:""},{id:"2",note:'A,"B"'}];
assert.deepEqual(parse(stringify(many)), many);
assert.throws(() => parse('note\n"foo"x'), /BAD_CSV_QUOTE/);
assert.equal(IDS.length, 50);
console.log("PACK02 empty one-column row: PASS");
